#!/usr/bin/env python3
"""Refresh contracts/runtime/minigame-api.json from the platform's API reference.

The common mini-game platform documents its API as one page per function,
linked from the reference index's sidebar: `<category path>/<ns>.<name>.html`,
where `<ns>` is the platform's global, the same on every top-level page, and a
class member is `<Class>.<member>.html` (capitalised). This reads every
top-level page off the index and writes the names with their category paths --
the list every other API contract is checked against.

The index URL is an argument rather than a constant: the repository carries no
platform's brand, and the URL is the platform's. A name that carries the brand
is published by migo under what it does instead -- the brand segment becomes
`Host` (an app update API is `updateHostApp`) -- and an adapter maps it back.

  python3 scripts/fetch-minigame-api-reference.py --index-url <reference index> [--check]

Network access, so not a gate: run it deliberately and review the diff, which
is the platform adding, moving or removing an API. --check only compares.
Standard library only.
"""

from __future__ import annotations

import argparse
import collections
import importlib.util
import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts/runtime/minigame-api.json"

# `.../api/<category>/<ns>.<name>.html`; the namespace is told apart from a class
# by case, and from other lowercase prefixes by being shared by every page.
PAGE = re.compile(r'href="[^"]*?/api/(?P<category>[a-z0-9/_-]+)/(?P<ns>[a-z]+)\.(?P<name>[A-Za-z0-9_]+)\.html"')

COMMENT = [
    "The common mini-game platform's API, by name: every top-level function and property its API reference documents,",
    "one page each, with the reference's category path. Generated by scripts/fetch-minigame-api-reference.py from the",
    "reference's own index -- run it deliberately and review the diff, which is the platform's API changing.",
    "",
    "A name that carries the platform's brand is listed under the name migo publishes it by, the brand segment",
    "replaced by `Host`; an adapter publishes it under the platform's name.",
    "",
    "Every API contract that speaks of the platform's API -- contracts/runtime/api-platform-matrix.json first -- is",
    "checked against this list, so an API the platform has and migo has not decided on is a failure, not a gap.",
]


def brand_pattern() -> re.Pattern[str]:
    """The repository hygiene gate's own brand rule, so the two cannot disagree."""
    spec = importlib.util.spec_from_file_location(
        "repository_hygiene", ROOT / "scripts/check-repository-hygiene.py"
    )
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    # Registered before it runs: its dataclasses look their module up by name.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    rules = [rule.pattern for rule in module._text_rules() if rule.name == "legacy brand namespace"]
    return re.compile("|".join(f"(?:{rule.pattern})" for rule in rules), re.IGNORECASE)


def migo_name(name: str, brand: re.Pattern[str]) -> str:
    renamed = brand.sub("Host", name)
    if brand.search(renamed):
        raise SystemExit(f"{name}: the brand is still in {renamed}; rename it by hand")
    return renamed


def reference(index_html: str) -> dict[str, str]:
    pages = [m.groupdict() for m in PAGE.finditer(index_html)]
    namespaces = collections.Counter(page["ns"] for page in pages)
    if not namespaces:
        raise SystemExit("no API pages in the index; is it the reference index?")
    namespace, count = namespaces.most_common(1)[0]
    if count < 100:
        raise SystemExit(f"only {count} pages share a namespace; the index's shape has changed")
    brand = brand_pattern()
    apis: dict[str, str] = {}
    for page in pages:
        if page["ns"] != namespace:
            continue
        name = migo_name(page["name"], brand)
        category = page["category"]
        if apis.get(name, category) != category:
            raise SystemExit(f"{name} is documented under both {apis[name]} and {category}")
        apis[name] = category
    return dict(sorted(apis.items()))


def render(apis: dict[str, str]) -> str:
    document = {"schema_version": 1, "$comment": COMMENT, "apis": apis}
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--index-url", help="the platform's API reference index")
    parser.add_argument("--index-file", type=pathlib.Path, help="a saved copy of the index instead")
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    if args.index_file:
        html = args.index_file.read_text(encoding="utf-8")
    elif args.index_url:
        with urllib.request.urlopen(args.index_url, timeout=60) as response:
            html = response.read().decode("utf-8")
    else:
        parser.error("--index-url or --index-file is required")
    text = render(reference(html))
    if args.check:
        current = CONTRACT.read_text(encoding="utf-8") if CONTRACT.exists() else ""
        if current != text:
            print(f"{CONTRACT.relative_to(ROOT)} differs from the reference", file=sys.stderr)
            return 1
        print(f"{CONTRACT.relative_to(ROOT)} matches the reference")
        return 0
    CONTRACT.write_text(text, encoding="utf-8")
    print(f"wrote {len(json.loads(text)['apis'])} APIs to {CONTRACT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
