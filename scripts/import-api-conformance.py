#!/usr/bin/env python3
"""Record what migo-conformance measured on one platform, per API.

The API x platform matrix says what is wired: which APIs reach a working path on each platform. That is not what a
game sees -- an API can be wired and answer with the wrong fields, the wrong errMsg, a made-up value. migo-conformance's
`api-spec` bundle checks each API against its reference (contracts/runtime/minigame-api-spec.json) on a real host, and
the bundles that go deeper into one API -- a request's bodies, a worker's messages -- name the API they check the same
way: `<bundle>/<api>/<check>`. This script turns one platform's run (migo-conformance's dist/results-<runner>.json, the
api-spec bundle and any others) into
contracts/runtime/api-conformance-<platform>.json, which the matrix generator reads: a cell is ready only where its API
was verified there, or is deliberately not offered, or is the host app's to answer.

A platform may be measured on more than one host -- Linux on the C ABI's minimal host and on the Qt Host Kit, its own
host layer -- and each answers for what it hosts: the Host Kit verifies what it answers itself, the C host what a C ABI
host supplies. So the record merges the runs: an API is verified where any run verified it, failing where none did
and one failed, present where every run only found it, absent where none did.

Per API, from the assertions that name it (api-spec's `api-spec/<api>/exists` says whether it is there at all):
  verified  it was exercised -- called, or listened to -- and every check passed;
  failing   a check failed (the ids are kept, so the record says what);
  present   it exists and nothing more was checked: the bundle does not call it blind (it shows UI, asks a permission,
            needs arguments), and no bundle has yet;
  absent    it does not exist on the platform.

A check of a call's shape alone -- api-surface-spec's, which calls every API blind and accepts fail as an answer --
never makes an API verified; when one fails, the API is failing (SHAPE_ONLY_BUNDLES).

The record carries, per run, when it was measured, by which runner, and against which commits, so a reader can tell
how old each part of it is.

  scripts/import-api-conformance.py --platform macos --runner macos \
      --results ../migo-conformance/dist/results-macos.json --conformance ../migo-conformance
  scripts/import-api-conformance.py --platform linux \
      --runner linux-capi --results capi.json --conformance ../migo-conformance --runtime ../migo-runtime \
      --runner linux-qt --results qt.json --conformance ../migo-conformance --runtime ../migo-runtime
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = "contracts/runtime/minigame-api-spec.json"
PLATFORMS = ("android", "ios", "macos", "linux", "windows", "ohos")
STATUSES = ("verified", "failing", "present", "absent")

# Bundles whose checks are about the shape of a call, not what it does. api-surface-spec calls every API blind -- with
# no options, or wrong ones -- and checks that it does not throw, ends in complete, and answers success or fail but not
# both. Most of those calls end in fail ("invalid url", "not supported"): the contract kept, not the API working. So a
# shape check never makes an API verified; one that fails still makes it failing, since an API that throws or breaks
# its callbacks when called wrong is broken.
SHAPE_ONLY_BUNDLES = frozenset({"api-surface-spec"})

COMMENT = [
    "What migo-conformance measured on this platform, per API of minigame-api-spec.json: the api-spec bundle and the",
    "bundles whose checks name an API (<bundle>/<api>/<check>). GENERATED by scripts/import-api-conformance.py from",
    "one or more runs' results -- do not edit; rerun the bundles and import again.",
    "",
    "verified: exercised (called or listened to) and every check passed; a check of the call's shape alone",
    "(api-surface-spec's blind calls) does not verify. failing: a check failed (ids kept). present:",
    "exists, and nothing more was checked -- api-spec does not call it blind, and no bundle has yet. absent:",
    "does not exist here. Several runs (one per host the platform is measured on) merge: verified where any run",
    "verified it, failing where none did and one failed. measured: per run, when, by which runner, against which",
    "commits of migo-runtime and migo-conformance.",
    "The API x platform matrix counts a cell ready only where its API is verified here (or is not offered, or is the",
    "host app's to answer).",
]


class Fail(SystemExit):
    def __init__(self, message: str) -> None:
        super().__init__(f"import-api-conformance: {message}")


def commit(directory: pathlib.Path) -> str:
    return subprocess.run(
        ["git", "-C", str(directory), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()


def statuses(results: dict, apis: list[str]) -> dict[str, dict]:
    by_api: dict[str, list[dict]] = {name: [] for name in apis}
    for row in results["results"]:
        parts = row["id"].split("/")
        if len(parts) < 3:
            continue
        if parts[0] == "api-spec" and parts[1] not in by_api:
            raise Fail(f"{row['id']}: {parts[1]} is not an API of the spec")
        # Another bundle's check names an API only where its second part is one; the rest name what they check.
        if parts[1] in by_api:
            by_api[parts[1]].append(row)
    recorded = {}
    for name, rows in by_api.items():
        if not rows:
            raise Fail(f"the run has no assertion for {name}: it is not a run of the whole api-spec bundle")
        exists = [row for row in rows if row["id"] == f"api-spec/{name}/exists"]
        if not exists:
            raise Fail(f"the run never asked whether {name} exists")
        if not exists[0]["passed"]:
            recorded[name] = {"status": "absent"}
            continue
        failing = sorted(row["id"] for row in rows if not row["passed"])
        exercised = [row for row in rows if row["id"].split("/")[0] not in SHAPE_ONLY_BUNDLES]
        if failing:
            recorded[name] = {"status": "failing", "failing": failing}
        elif len(exercised) > 1:
            recorded[name] = {"status": "verified"}
        else:
            recorded[name] = {"status": "present"}
    return recorded


def merged(runs: list[dict[str, dict]]) -> dict[str, dict]:
    """One record from several runs' statuses: the best answer any run gave for each API."""
    record = {}
    for name in runs[0]:
        entries = [run[name] for run in runs]
        statuses = {entry["status"] for entry in entries}
        if "verified" in statuses:
            record[name] = {"status": "verified"}
        elif "failing" in statuses:
            failing = sorted({check for entry in entries for check in entry.get("failing", [])})
            record[name] = {"status": "failing", "failing": failing}
        elif "present" in statuses:
            record[name] = {"status": "present"}
        else:
            record[name] = {"status": "absent"}
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--platform", required=True, choices=PLATFORMS, help="the matrix's platform the runs stand for")
    # One run per --runner/--results pair, in order; --conformance, --runtime and --date likewise, or once for all.
    parser.add_argument("--runner", required=True, action="append",
                        help="the conformance runner that produced a run (e.g. ios-simulator)")
    parser.add_argument("--results", required=True, action="append", type=pathlib.Path,
                        help="migo-conformance dist/results-<runner>.json")
    parser.add_argument("--conformance", required=True, action="append", type=pathlib.Path,
                        help="the migo-conformance checkout a run ran")
    parser.add_argument("--runtime", action="append", type=pathlib.Path,
                        help="the migo-runtime checkout a run ran against (default: this one)")
    parser.add_argument("--date", action="append", help="when a run was measured (YYYY-MM-DD; default: its results file's)")
    args = parser.parse_args()

    count = len(args.runner)
    if len(args.results) != count:
        raise Fail(f"{count} runner(s) and {len(args.results)} results file(s): give one of each per run")

    def per_run(values, default, what):
        values = values or [default]
        if len(values) == 1:
            return values * count
        if len(values) != count:
            raise Fail(f"{len(values)} {what} for {count} run(s): give one, or one per run")
        return values

    conformance = per_run(args.conformance, None, "--conformance")
    runtime = per_run(args.runtime, ROOT, "--runtime")
    dates = per_run(args.date, None, "--date")

    apis = sorted(json.loads((ROOT / SPEC).read_text())["apis"])
    runs, measured = [], []
    for index in range(count):
        results = json.loads(args.results[index].read_text())
        runs.append(statuses(results, apis))
        measured.append({
            "date": dates[index] or datetime.date.fromtimestamp(args.results[index].stat().st_mtime).isoformat(),
            "runner": args.runner[index],
            "bundles": sorted({row["id"].split("/")[0] for row in results["results"]}),
            "runtime": commit(runtime[index]),
            "conformance": commit(conformance[index]),
        })
    recorded = merged(runs)

    out = ["{", '  "schema_version": 2,', '  "$comment": [']
    out += [f"    {json.dumps(line)}," for line in COMMENT[:-1]]
    out.append(f"    {json.dumps(COMMENT[-1])}")
    out += ["  ],", f'  "platform": {json.dumps(args.platform)},', '  "measured": [']
    out += [f"    {json.dumps(run)}{',' if position + 1 < count else ''}" for position, run in enumerate(measured)]
    out += ["  ],", '  "apis": {']
    for position, name in enumerate(apis):
        tail = "," if position + 1 < len(apis) else ""
        out.append(f"    {json.dumps(name)}: {json.dumps(recorded[name])}{tail}")
    out += ["  }", "}"]
    target = ROOT / f"contracts/runtime/api-conformance-{args.platform}.json"
    target.write_text("\n".join(out) + "\n")
    counts = {status: sum(1 for entry in recorded.values() if entry["status"] == status) for status in STATUSES}
    print(f"{target.relative_to(ROOT)}: {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
