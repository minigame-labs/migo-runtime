#!/usr/bin/env python3
"""Record what migo-conformance measured on one platform, per API.

The API x platform matrix says what is wired: which APIs reach a working path on each platform. That is not what a
game sees -- an API can be wired and answer with the wrong fields, the wrong errMsg, a made-up value. migo-conformance's
`api-spec` bundle checks each API against its reference (contracts/runtime/minigame-api-spec.json) on a real host, and
the bundles that go deeper into one API -- a request's bodies, a worker's messages -- name the API they check the same
way: `<bundle>/<api>/<check>`. This script turns one platform's run (migo-conformance's dist/results-<runner>.json, the
api-spec bundle and any others) into
contracts/runtime/api-conformance-<platform>.json, which the matrix generator reads: a cell is ready only where its API
was verified there, or is deliberately not offered, or is the host app's to answer.

Per API, from the assertions that name it (api-spec's `api-spec/<api>/exists` says whether it is there at all):
  verified  it was exercised -- called, or listened to -- and every check passed;
  failing   a check failed (the ids are kept, so the record says what);
  present   it exists and nothing more was checked: the bundle does not call it blind (it shows UI, asks a permission,
            needs arguments), and no bundle has yet;
  absent    it does not exist on the platform.

The record carries when it was measured and against which commits, so a reader can tell how old it is.

  scripts/import-api-conformance.py --platform macos --runner macos \
      --results ../migo-conformance/dist/results-macos.json --conformance ../migo-conformance
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = "contracts/runtime/minigame-api-spec.json"
PLATFORMS = ("android", "ios", "macos", "linux", "windows", "ohos")
STATUSES = ("verified", "failing", "present", "absent")

COMMENT = [
    "What migo-conformance measured on this platform, per API of minigame-api-spec.json: the api-spec bundle and the",
    "bundles whose checks name an API (<bundle>/<api>/<check>). GENERATED by scripts/import-api-conformance.py from one",
    "run's results -- do not edit; rerun the bundles and import again.",
    "",
    "verified: exercised (called or listened to) and every check passed. failing: a check failed (ids kept). present:",
    "exists, and nothing more was checked -- api-spec does not call it blind, and no bundle has yet. absent:",
    "does not exist here. measured: when, by which runner, against which commits of migo-runtime and migo-conformance.",
    "The API x platform matrix counts a cell ready only where its API is verified here (or is not offered, or is the",
    "host app's to answer).",
]


class Fail(SystemExit):
    def __init__(self, message: str) -> None:
        super().__init__(f"import-api-conformance: {message}")


def commit(directory: pathlib.Path) -> str:
    return subprocess.run(
        ["git", "-C", str(directory), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()


def statuses(results: dict, apis: list[str]) -> dict[str, dict]:
    by_api: dict[str, list[dict]] = {name: [] for name in apis}
    for row in results["results"]:
        parts = row["id"].split("/")
        if len(parts) < 3:
            continue
        if parts[0] == "api-spec" and parts[1] not in by_api:
            raise Fail(f"{row['id']}: {parts[1]} is not an API of the spec")
        # Another bundle's check names an API only where its second part is one; the rest name what they check.
        if parts[1] in by_api:
            by_api[parts[1]].append(row)
    recorded = {}
    for name, rows in by_api.items():
        if not rows:
            raise Fail(f"the run has no assertion for {name}: it is not a run of the whole api-spec bundle")
        exists = [row for row in rows if row["id"] == f"api-spec/{name}/exists"]
        if not exists:
            raise Fail(f"the run never asked whether {name} exists")
        if not exists[0]["passed"]:
            recorded[name] = {"status": "absent"}
            continue
        failing = sorted(row["id"] for row in rows if not row["passed"])
        if failing:
            recorded[name] = {"status": "failing", "failing": failing}
        elif len(rows) > 1:
            recorded[name] = {"status": "verified"}
        else:
            recorded[name] = {"status": "present"}
    return recorded


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--platform", required=True, choices=PLATFORMS, help="the matrix's platform the run stands for")
    parser.add_argument("--runner", required=True, help="the conformance runner that produced it (e.g. ios-simulator)")
    parser.add_argument("--results", required=True, type=pathlib.Path, help="migo-conformance dist/results-<runner>.json")
    parser.add_argument("--conformance", required=True, type=pathlib.Path, help="the migo-conformance checkout it ran")
    parser.add_argument("--runtime", type=pathlib.Path, default=ROOT, help="the migo-runtime checkout it ran against")
    parser.add_argument("--date", help="when it was measured (YYYY-MM-DD; default: the results file's)")
    args = parser.parse_args()

    apis = sorted(json.loads((ROOT / SPEC).read_text())["apis"])
    results = json.loads(args.results.read_text())
    recorded = statuses(results, apis)
    date = args.date or datetime.date.fromtimestamp(args.results.stat().st_mtime).isoformat()
    bundles = sorted({row["id"].split("/")[0] for row in results["results"]})
    measured = {
        "date": date,
        "runner": args.runner,
        "bundles": bundles,
        "runtime": commit(args.runtime),
        "conformance": commit(args.conformance),
    }
    out = ["{", '  "schema_version": 1,', '  "$comment": [']
    out += [f"    {json.dumps(line)}," for line in COMMENT[:-1]]
    out.append(f"    {json.dumps(COMMENT[-1])}")
    out += ["  ],", f'  "platform": {json.dumps(args.platform)},', f'  "measured": {json.dumps(measured)},', '  "apis": {']
    for position, name in enumerate(apis):
        tail = "," if position + 1 < len(apis) else ""
        out.append(f"    {json.dumps(name)}: {json.dumps(recorded[name])}{tail}")
    out += ["  }", "}"]
    target = ROOT / f"contracts/runtime/api-conformance-{args.platform}.json"
    target.write_text("\n".join(out) + "\n")
    counts = {status: sum(1 for entry in recorded.values() if entry["status"] == status) for status in STATUSES}
    print(f"{target.relative_to(ROOT)}: {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
