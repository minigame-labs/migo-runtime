#!/usr/bin/env python3
"""The common mini-game platform's API, as its reference documents it, in a form a program can check.

contracts/runtime/minigame-api-spec.json records, for every API in contracts/runtime/minigame-api.json, the facts its
reference page states: how it is called (an options object with success/fail/complete, a listener, a value returned,
an object made), whether it can be called in Promise style, the options it takes, the fields its success result,
return value or listener argument carries -- names and types, one level of structure deep -- the authorization scope
it needs, which of the reference's desktop and HarmonyOS clients support it, and whether it is deprecated. Facts only:
no description is copied.

The source is the reference's local mirror, docs/minigame-reference/ (gitignored, fetched by hand; its README says
when). This script reads it and writes the contract; `--check` regenerates in memory and fails if the committed
contract differs, which is how a refetch of the mirror shows what the reference changed. Where the mirror is absent --
a CI runner -- `--check` checks only that the contract covers the platform's API list exactly.

The contract is what the verification lane checks implementations against: a result's fields and types, a failure's
errMsg, Promise support.
"""

from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIRROR = "docs/minigame-reference"
API_LIST = "contracts/runtime/minigame-api.json"
CONTRACT = "contracts/runtime/minigame-api-spec.json"

# This repository names the reference's host app `Host` (`updateHostApp`): such an API's page is the one in its
# category whose name is this one with `Host` standing for the app's name in capitalised words -- and exactly one
# must be.
HOST = "Host"

COMMENT = [
    "The common mini-game platform's API as its reference documents it, for every API in minigame-api.json.",
    "GENERATED by scripts/gen-minigame-api-spec.py from a local mirror of the reference, which is not shipped:",
    "do not edit; refetch the mirror and regenerate. Facts only, no description is copied.",
    "",
    "kind: callback (an options object with success/fail/complete), event (on*/off* with a listener), sync (returns",
    "a value), factory (returns an object of a class the reference documents), void (returns nothing, no callbacks).",
    "returns: the type the signature names, or null. params: the signature's parameters. promise: whether",
    "Promise-style calls are supported, null where the page does not say. scope: the authorization scope the call",
    "needs, by the engine's name for it. clients: what the page says of the reference's Windows, Mac and HarmonyOS",
    "clients -- true, false, or {\"from\": version} -- absent when it says nothing. options: the options object's fields other than the",
    "callbacks. success / result / listener: the fields of the success callback's argument, of the returned object,",
    "of the listener's argument. A field is [name, type] or [name, type, since], then an object with what else the page",
    "says of it: \"fields\", the fields of an Object it details; \"when\", that it is there only sometimes -- plugin,",
    "host-app (the game runs inside a third-party app), darkmode, option:<name> (that option was passed),",
    "without:<name> (it was not), chat (opened from a chat), or only:<ios|android|pc|mobile>. methods: the methods",
    "the reference documents for the class the API returns. deprecated, since: from the reference's index.",
]

CLIENTS = {"Windows": "windows", "Mac": "mac", "鸿蒙 OS": "harmony"}
# The engine's own scope names (`Scope::as_str`): a scope the reference names with its app's prefix is recorded by
# the engine's name for it.
SCOPES = "engine/crates/shared/src/services/permission.rs"


def engine_scopes(root: pathlib.Path) -> list[str]:
    return re.findall(r'=> "(scope\.\w+)"', (root / SCOPES).read_text())


def scope_name(described: str, known: list[str]) -> str:
    """The reference's scope as the engine names it: a repeated `scope.` prefix (a typo on one page) collapsed, and a
    name that is the engine's behind the reference's app prefix (one capitalised word, then the engine's name
    capitalised) recorded as the engine's."""
    name = re.sub(r"^(scope\.)+", "scope.", described)
    tail = name[len("scope."):]
    for scope in known:
        own = scope[len("scope."):]
        if tail == own or re.fullmatch(r"[A-Z][a-z]+" + re.escape(own[:1].upper() + own[1:]), tail):
            return scope
    return name


def client_support(words: str):
    """What a page says of one client: true, false, or {"from": version} for support from a client version."""
    if words == "支持":
        return True
    if words == "不支持":
        return False
    version = re.search(r"(\d+\.\d+(?:\.\d+)?)", words)
    if words.startswith("支持") and version:
        return {"from": version.group(1)}
    raise Fail(f"a client's support reads {words!r}, which this script does not understand")


class Fail(SystemExit):
    def __init__(self, message: str) -> None:
        super().__init__(f"gen-minigame-api-spec: {message}")


def plain(text: str) -> str:
    """A cell without markdown: links reduced to their text, code spans to their content."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return text.replace("`", "").strip()


def table_at(lines: list[str], start: int) -> tuple[list[str], list[list[str]], int]:
    """The markdown table starting at `start`: its header cells, its rows, and the line after it."""
    def cells(line: str) -> list[str]:
        return [cell.strip() for cell in line.strip().strip("|").split("|")]

    header = cells(lines[start])
    rows = []
    at = start + 2
    while at < len(lines) and lines[at].startswith("|"):
        rows.append(cells(lines[at]))
        at += 1
    return header, rows, at


def first_table(lines: list[str], start: int, stop: int) -> int | None:
    for index in range(start, min(stop, len(lines) - 1)):
        if lines[index].startswith("| ") and re.match(r"^\|\s*-", lines[index + 1]):
            return index
    return None


# When the reference says a field is there only sometimes: the phrasings it uses, and what each means. A field
# whose description matches none of these is always there.
CONDITIONS = (
    (r"在插件中调用时", "plugin"),  # only when called inside a plugin
    (r"第三方\s*[Aa]pp", "host-app"),  # only when the game runs inside a third-party app
    (r'"darkmode":\s*true', "darkmode"),  # only with the darkmode configuration, which mini-games lack
    (r"仅当\s*([A-Za-z]+)\s*传\s*true", r"option:\1"),  # only when that option is true
    (r"没传入\s*([A-Za-z]+)", r"without:\1"),  # only when that option was not passed
    (r"传入\s*([A-Za-z]+)\s*时", r"option:\1"),  # only when that option was passed
    (r"withSubscriptions", "option:withSubscriptions"),  # only when that option is true
    (r"群聊/单聊打开", "chat"),  # only when opened from a chat
    (r"仅在\s*PC\s*端|仅\s*PC", "only:pc"),
    # Before the one-platform rules: "仅 iOS 和 Android 端支持" names both, and "仅 iOS" would read it as one.
    (r"iOS\s*和\s*Android\s*端", "only:mobile"),
    (r"仅\s*iOS", "only:ios"),
    (r"仅\s*Android", "only:android"),
)


def condition_of(description: str) -> str | None:
    for pattern, condition in CONDITIONS:
        found = re.search(pattern, description)
        if found:
            return found.expand(condition)
    return None


def fields_of(header: list[str], rows: list[list[str]]) -> list[list]:
    """[name, type] or [name, type, since] per row of a property table, then {"when": condition} where the reference
    says the field is there only sometimes."""
    columns = {name: index for index, name in enumerate(header)}
    name_at = columns.get("属性", columns.get("结构属性", 0))
    type_at = columns.get("类型", 1)
    since_at = columns.get("最低版本")
    note_at = columns.get("说明")
    fields: list[list] = []
    for row in rows:
        if len(row) <= max(name_at, type_at):
            continue
        name, kind = plain(row[name_at]), plain(row[type_at])
        if not name:
            continue
        field: list = [name, kind]
        if since_at is not None and since_at < len(row) and plain(row[since_at]):
            field.append(plain(row[since_at]))
        condition = condition_of(row[note_at]) if note_at is not None and note_at < len(row) else None
        if condition:
            field.append({"when": condition})
        fields.append(field)
    return fields


def details(field: list) -> dict:
    """The field's trailing object, made when it has none."""
    if not (field and isinstance(field[-1], dict)):
        field.append({})
    return field[-1]


def headings(lines: list[str]) -> list[tuple[int, int, str]]:
    """(line, level, title) for every heading."""
    found = []
    for index, line in enumerate(lines):
        match = re.match(r"^(#{1,6})\s+(.*)$", line)
        if match:
            found.append((index, len(match.group(1)), match.group(2).strip()))
    return found


def section_end(heads: list[tuple[int, int, str]], at: int, total: int) -> int:
    level = heads[at][1]
    for line, other, _ in heads[at + 1 :]:
        if other <= level:
            return line
    return total


def structured(lines: list[str], start: int, stop: int) -> list[list]:
    """The first property table in [start, stop), with the `↳ name` tables after it attached to their fields."""
    at = first_table(lines, start, stop)
    if at is None:
        return []
    header, rows, index = table_at(lines, at)
    fields = fields_of(header, rows)
    by_name = {field[0]: field for field in fields}
    while index < stop:
        match = re.match(r"^\*\*↳ `([^`]+)`\*\*", lines[index])
        if match:
            table = first_table(lines, index + 1, stop)
            if table is None:
                break
            sub_header, sub_rows, index = table_at(lines, table)
            target = by_name.get(match.group(1))
            if target is not None and "属性" in "".join(sub_header):
                details(target)["fields"] = fields_of(sub_header, sub_rows)
            continue
        if lines[index].startswith("#"):
            break
        index += 1
    return fields


def spec_of(markdown: str, namespace: str, name: str, scopes: list[str]) -> dict:
    lines = markdown.split("\n")
    heads = headings(lines)
    title = next(text for _, level, text in heads if level == 1)
    match = re.match(rf"^(?:(\S+?)\s+)?{re.escape(namespace)}\.(\w+)\((.*)\)$", title)
    if not match:
        raise Fail(f"{name}: the page's title is not a signature: {title!r}")
    returns = plain(match.group(1)) if match.group(1) else None
    params = [param.strip() for param in match.group(3).split(",") if param.strip()]

    promise = None
    scope = None
    clients: dict[str, object] = {}
    for line in lines:
        if not line.startswith(">"):
            continue
        note = line[1:].strip().rstrip("\\").strip()
        found = re.match(r"^以 Promise 风格 调用：(.*)$", note)
        if found:
            words = found.group(1).strip()
            promise = {"支持": True, "不支持": False}.get(words, words)
        found = re.search(r"需要 (scope\.[\w.]+)", note)
        if found:
            scope = scope_name(found.group(1), scopes)
        # "<the reference's app> <client> 版：<support>"
        found = re.match(r"^\S+ (Windows|Mac|鸿蒙 OS) 版：(.*)$", note)
        if found:
            clients[CLIENTS[found.group(1)]] = client_support(plain(found.group(2)))

    options: list[list] = []
    callbacks = False
    for index, (line, level, text) in enumerate(heads):
        if level == 3 and re.match(r"^(Object|object) \w+$", text):
            table = first_table(lines, line + 1, section_end(heads, index, len(lines)))
            if table is not None:
                header, rows, _ = table_at(lines, table)
                for field in fields_of(header, rows):
                    if field[0] in ("success", "fail", "complete"):
                        callbacks = True
                    else:
                        options.append(field)
            break

    def section(predicate) -> list[list]:
        for index, (line, level, text) in enumerate(heads):
            if predicate(level, text):
                return structured(lines, line + 1, section_end(heads, index, len(lines)))
        return []

    success = section(lambda level, text: text.startswith("object.success 回调函数"))
    result = section(lambda level, text: level == 2 and text == "返回值")
    is_event = re.match(r"^(on|off)[A-Z]", name) is not None and (not params or params[0].startswith("function "))
    listener = section(lambda level, text: level == 3 and text.startswith("function ")) if (
        is_event and name.startswith("on")
    ) else []

    if is_event:
        kind = "event"
    elif callbacks:
        kind = "callback"
    elif returns is not None and returns[0].isupper() and returns not in ("Object", "Boolean", "Number", "String"):
        kind = "factory"
    elif returns is not None:
        kind = "sync"
    else:
        kind = "void"
    spec: dict[str, object] = {"kind": kind, "returns": returns, "params": params, "promise": promise}
    if scope:
        spec["scope"] = scope
    if clients:
        spec["clients"] = clients
    for key, value in (("options", options), ("success", success), ("result", result), ("listener", listener)):
        if value:
            spec[key] = value
    return spec


def generate(root: pathlib.Path) -> str:
    mirror = root / MIRROR
    index = json.loads((mirror / "index.json").read_text())
    apis = json.loads((root / API_LIST).read_text())["apis"]
    scopes = engine_scopes(root)
    # The reference's namespace: the prefix its function pages' titles share.
    namespaces = collections.Counter(
        entry["title"].split(".", 1)[0]
        for entry in index
        if entry["kind"] == "function" and re.match(r"^[a-z]+\.\w+$", entry["title"])
    )
    namespace = namespaces.most_common(1)[0][0]
    pages = {}
    for entry in index:
        title = entry["title"]
        if entry["kind"] == "function" and title.startswith(namespace + "."):
            pages.setdefault(title[len(namespace) + 1 :], entry)
    # The methods the reference documents for each class an API returns.
    methods: dict[str, set[str]] = collections.defaultdict(set)
    for entry in index:
        owner = entry.get("parent_class")
        if entry["kind"] == "method" and owner and entry["title"].startswith(owner + "."):
            methods[owner].add(entry["title"][len(owner) + 1 :])
    specs = {}
    for name in sorted(apis):
        if name == "env":
            # A property, not a call: the environment's paths.
            specs[name] = {"kind": "property"}
            continue
        entry = pages.get(name)
        if entry is None and HOST in name:
            pattern = re.compile("^" + re.escape(name).replace(HOST, "(?:[A-Z][a-z]+)+") + "$")
            category = apis[name]
            candidates = [
                page for page_name, page in pages.items()
                if pattern.match(page_name) and page["path"].startswith(category + "/")
            ]
            if len(candidates) > 1:
                raise Fail(f"{name} matches {len(candidates)} pages in {category}")
            entry = candidates[0] if candidates else None
        if entry is None:
            raise Fail(f"the mirror has no page for {name}")
        page_name = entry["title"][len(namespace) + 1 :]
        spec = spec_of((mirror / entry["md_file"]).read_text(), namespace, page_name, scopes)
        if spec.get("returns") in methods:
            spec["methods"] = sorted(methods[spec["returns"]])
        if entry.get("deprecated"):
            spec["deprecated"] = True
        if entry.get("min_base_library"):
            spec["since"] = entry["min_base_library"]
        specs[name] = spec
    fetched = re.search(r"\*\*Fetched:\*\* (\S+)", (mirror / "README.md").read_text())
    out = ["{", '  "schema_version": 1,', '  "$comment": [']
    out += [f"    {json.dumps(line, ensure_ascii=False)}," for line in COMMENT[:-1]]
    out.append(f"    {json.dumps(COMMENT[-1], ensure_ascii=False)}")
    out.append("  ],")
    out.append(f'  "fetched": {json.dumps(fetched.group(1) if fetched else None)},')
    out.append('  "apis": {')
    names = sorted(specs)
    for position, name in enumerate(names):
        tail = "," if position + 1 < len(names) else ""
        out.append(f"    {json.dumps(name)}: {json.dumps(specs[name], ensure_ascii=False)}{tail}")
    out += ["  }", "}"]
    text = "\n".join(out) + "\n"
    json.loads(text)
    return text


def check_coverage(root: pathlib.Path) -> None:
    contract = json.loads((root / CONTRACT).read_text())
    apis = set(json.loads((root / API_LIST).read_text())["apis"])
    covered = set(contract["apis"])
    if covered != apis:
        raise Fail(
            f"{CONTRACT} does not cover minigame-api.json exactly: missing {sorted(apis - covered)[:5]}, "
            f"extra {sorted(covered - apis)[:5]}"
        )
    kinds = {"callback", "event", "sync", "factory", "void", "property"}
    for name, spec in contract["apis"].items():
        if spec.get("kind") not in kinds:
            raise Fail(f"{name}: kind {spec.get('kind')!r} is not one of {sorted(kinds)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail if the committed contract is stale")
    args = parser.parse_args()
    root = args.root
    if args.check:
        check_coverage(root)
        if not (root / MIRROR / "index.json").exists():
            print(f"gen-minigame-api-spec: {MIRROR} is not here; checked coverage only")
            return 0
        if generate(root) != (root / CONTRACT).read_text():
            raise Fail(f"{CONTRACT} is stale: regenerate it with scripts/gen-minigame-api-spec.py and review the diff")
        print("gen-minigame-api-spec: the contract is what the mirror says")
        return 0
    (root / CONTRACT).write_text(generate(root))
    check_coverage(root)
    contract = json.loads((root / CONTRACT).read_text())["apis"]
    kinds = collections.Counter(spec["kind"] for spec in contract.values())
    promise = sum(1 for spec in contract.values() if spec.get("promise") is True)
    print(f"{len(contract)} APIs: {dict(kinds)}; Promise style supported by {promise}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
