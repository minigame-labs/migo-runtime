#!/usr/bin/env python3
"""Write the Swift SDK's host-service numbers from the channel's contract.

contracts/runtime/host-services.json defines every service, method and event
number of the host-service channel. The C header and the library's Rust
constants are held to it by scripts/test-host-services-contract.sh; a Swift app
that imports only a product module (MigoMacV8, MigoApplePerformancePlus) sees
neither, so the SDK carries the numbers itself -- generated here, never written
by hand, and checked by the same gate (--check).

  python3 scripts/gen-swift-host-services.py [--root DIR] [--check]

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

CONTRACT = "contracts/runtime/host-services.json"
OUTPUT = "platforms/apple/Sources/MigoAppleRenderer/MigoHostServiceNumbers.swift"


def camel(name: str, upper: bool) -> str:
    parts = name.split("_")
    head = parts[0].capitalize() if upper else parts[0]
    return head + "".join(part.capitalize() for part in parts[1:])


def render(contract: dict) -> str:
    services = sorted(contract["services"].items(), key=lambda item: item[1]["id"])
    out = [
        "// GENERATED by scripts/gen-swift-host-services.py from contracts/runtime/host-services.json --",
        "// do not edit; change the contract and regenerate. scripts/test-host-services-contract.sh checks it.",
        "",
        "extension MigoHostServiceID {",
    ]
    for name, service in services:
        out.append(f"    public static let {camel(name, False)} = Self(rawValue: {service['id']})")
    out.append("")
    out.append("    /// Every service this SDK knows, in number order.")
    out.append("    public static let all: [Self] = [")
    out.append("        " + ", ".join(f".{camel(name, False)}" for name, _ in services) + ",")
    out.append("    ]")
    for name, service in services:
        out.append("")
        out.append(f"    /// `{name}`'s method and event numbers, as `include/migo/host_services.h` documents them.")
        out.append(f"    public enum {camel(name, True)} {{")
        for method, entry in sorted(service["methods"].items(), key=lambda item: item[1]["id"]):
            kind = "a call, answered once" if entry["kind"] == "call" else "a command, unanswered"
            out.append(f"        /// `{method}`: {kind}.")
            out.append(f"        public static let {camel(method, False)}: UInt32 = {entry['id']}")
        events = sorted(service.get("events", {}).items(), key=lambda item: item[1]["id"])
        if events:
            out.append("")
            out.append("        /// The service's events, for `postHostServiceEvent`.")
            out.append("        public enum Event {")
            for event, entry in events:
                out.append(f"            public static let {camel(event, False)}: UInt32 = {entry['id']}")
            out.append("        }")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    text = render(json.loads((args.root / CONTRACT).read_text(encoding="utf-8")))
    target = args.root / OUTPUT
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"{OUTPUT} does not match {CONTRACT}; run scripts/gen-swift-host-services.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} matches {CONTRACT}")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
