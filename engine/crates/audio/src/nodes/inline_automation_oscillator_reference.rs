use std::any::Any;

use shared::protocol::audio_cmd::AudioNodeId;

use crate::param::AudioParamTimeline;

use super::AudioNodeProcessor;

/// Waveform type for OscillatorNode
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OscillatorType {
    Sine,
    Square,
    Sawtooth,
    Triangle,
}

impl OscillatorType {
    pub fn from_str(s: &str) -> Self {
        match s {
            "square" => Self::Square,
            "sawtooth" => Self::Sawtooth,
            "triangle" => Self::Triangle,
            _ => Self::Sine,
        }
    }
}

/// Polynomial band-limited step, used to cancel the aliasing a discontinuity
/// causes.
///
/// A naive square or sawtooth is generated by evaluating an ideal, infinitely
/// sharp edge at discrete times. That edge contains energy above Nyquist, which
/// folds back down as inharmonic tones -- the buzzy, gritty quality of a
/// "digital" oscillator, worst at high frequencies where the folded partials land
/// in the middle of the spectrum. PolyBLEP subtracts a two-sample polynomial
/// approximation of the band-limited step around each discontinuity, which
/// removes most of that energy for two multiply-adds per edge.
///
/// `t` is the phase in `[0, 1)` and `dt` the phase increment per sample.
#[inline]
fn poly_blep(t: f64, dt: f64) -> f64 {
    if t < dt {
        // Just after the edge.
        let x = t / dt;
        2.0 * x - x * x - 1.0
    } else if t > 1.0 - dt {
        // Just before the next edge.
        let x = (t - 1.0) / dt;
        x * x + 2.0 * x + 1.0
    } else {
        0.0
    }
}

pub struct OscillatorNode {
    id: AudioNodeId,
    frequency: AudioParamTimeline,
    detune: AudioParamTimeline,
    frequency_values: Vec<f32>,
    detune_values: Vec<f32>,
    osc_type: OscillatorType,
    phase: f64,
    /// Running integral of the band-limited square, which is the triangle.
    triangle: f64,
    started: bool,
    stopped: bool,
    start_when: f64,
    stop_when: f64,
    start_origin: Option<f64>,
    phase_started: bool,
}

impl OscillatorNode {
    pub fn new(id: AudioNodeId, sample_rate: u32) -> Self {
        // Nyquist for the rate actually in use. This was hardcoded to 22050,
        // which is only right at 44.1 kHz: at the 48 kHz most devices run it
        // rejected the top 2 kHz of the legal range.
        let nyquist = (sample_rate.max(2) / 2) as f32;
        Self {
            id,
            // Default frequency: 440 Hz (A4)
            frequency: AudioParamTimeline::new(440.0, -nyquist, nyquist),
            // Default detune: 0 cents
            detune: AudioParamTimeline::new(0.0, -153600.0, 153600.0),
            frequency_values: Vec::new(),
            detune_values: Vec::new(),
            osc_type: OscillatorType::Sine,
            phase: 0.0,
            triangle: 0.0,
            started: false,
            stopped: false,
            start_when: 0.0,
            stop_when: f64::INFINITY,
            start_origin: None,
            phase_started: false,
        }
    }

    pub fn set_type(&mut self, t: OscillatorType) {
        self.osc_type = t;
    }

    pub fn start(&mut self, when: f64) {
        if self.started || self.stopped {
            return;
        }
        self.started = true;
        self.start_when = when;
    }

    pub fn stop(&mut self, when: f64) {
        if self.stopped {
            return;
        }
        self.stop_when = when;
    }

    /// Generate one band-limited sample and advance the phase.
    ///
    /// `phase_inc` is cycles per sample, so it is also the normalised distance
    /// PolyBLEP has to smooth each discontinuity over.
    #[inline]
    fn next_sample(&mut self, phase_inc: f64) -> f32 {
        let dt = phase_inc.abs().min(0.5);
        let phase = self.phase;

        let sample = match self.osc_type {
            OscillatorType::Sine => (phase * std::f64::consts::TAU).sin(),
            OscillatorType::Sawtooth => 2.0 * phase - 1.0 - poly_blep(phase, dt),
            OscillatorType::Square | OscillatorType::Triangle => {
                let naive = if phase < 0.5 { 1.0 } else { -1.0 };
                // Two edges per cycle: the rise at 0 and the fall at 0.5.
                let square = naive + poly_blep(phase, dt) - poly_blep((phase + 0.5).fract(), dt);
                if self.osc_type == OscillatorType::Square {
                    square
                } else {
                    // A triangle is the integral of a square, so integrating the
                    // band-limited one gives a band-limited triangle without a
                    // second correction polynomial. The 0.999 leak drains the DC
                    // that accumulates from rounding; without it a long-running
                    // oscillator slowly walks off centre.
                    self.triangle = self.triangle * 0.999 + 4.0 * dt * square;
                    self.triangle
                }
            }
        };

        self.phase = (self.phase + phase_inc).fract();
        sample as f32
    }
}

impl AudioNodeProcessor for OscillatorNode {
    fn id(&self) -> AudioNodeId {
        self.id
    }

    fn as_any_mut(&mut self) -> &mut dyn Any {
        self
    }

    fn is_finished(&self) -> bool {
        self.stopped
    }

    fn is_producing(&self) -> bool {
        self.started && !self.stopped
    }

    fn process(
        &mut self,
        _inputs: &[f32],
        output: &mut [f32],
        sample_rate: u32,
        channels: u32,
        current_time: f64,
    ) -> usize {
        let channels = channels.max(1) as usize;
        let frames = output.len() / channels;
        let clock = crate::render_time::RenderTime::new(current_time, sample_rate);
        let stopped = clock.stopped(self.stop_when, frames);
        if self.stopped || !self.started || frames == 0 {
            output[..frames * channels].fill(0.0);
            self.stopped |= stopped;
            return 0;
        }
        let origin = *self
            .start_origin
            .get_or_insert(self.start_when.max(current_time));
        let active = clock.active(origin, self.stop_when, frames);
        output[..active.start * channels].fill(0.0);
        output[active.end * channels..frames * channels].fill(0.0);
        if active.is_empty() {
            self.stopped |= stopped;
            return 0;
        }
        let current_time = clock.at(active.start);
        let output = &mut output[active.start * channels..active.end * channels];
        let frames = active.len();

        let sr = sample_rate.max(1) as f64;
        let frequency_automated = self.frequency.has_automation();
        let detune_automated = self.detune.has_automation();
        if frequency_automated || detune_automated {
            if frequency_automated {
                if self.frequency_values.len() < frames {
                    self.frequency_values.resize(frames, 0.0);
                }
                self.frequency.compute_values(
                    current_time,
                    &mut self.frequency_values[..frames],
                    sample_rate,
                );
            }
            if detune_automated {
                if self.detune_values.len() < frames {
                    self.detune_values.resize(frames, 0.0);
                }
                self.detune.compute_values(
                    current_time,
                    &mut self.detune_values[..frames],
                    sample_rate,
                );
            }
            let static_frequency = self.frequency.value() as f64;
            let static_detune = self.detune.value() as f64;
            let static_multiplier = (2.0f64).powf(static_detune / 1200.0);
            if !self.phase_started {
                let frequency = if frequency_automated {
                    self.frequency_values[0] as f64
                } else {
                    static_frequency
                };
                let detune = if detune_automated {
                    self.detune_values[0] as f64
                } else {
                    static_detune
                };
                self.phase =
                    ((current_time - origin).max(0.0) * frequency * 2.0_f64.powf(detune / 1200.0))
                        .fract();
                self.phase_started = true;
            }
            for frame in 0..frames {
                let frequency = if frequency_automated {
                    self.frequency_values[frame] as f64
                } else {
                    static_frequency
                };
                let multiplier = if detune_automated {
                    (2.0f64).powf(self.detune_values[frame] as f64 / 1200.0)
                } else {
                    static_multiplier
                };
                let sample = self.next_sample(frequency * multiplier / sr);
                output[frame * channels..(frame + 1) * channels].fill(sample);
            }
            self.stopped |= stopped;
            return frames;
        }
        let freq = self.frequency.compute_value(current_time) as f64;
        let detune = self.detune.compute_value(current_time) as f64;
        let computed_freq = freq * (2.0f64).powf(detune / 1200.0);
        let phase_inc = computed_freq / sr;
        if !self.phase_started {
            self.phase = ((current_time - origin).max(0.0) * computed_freq).fract();
            self.phase_started = true;
        }

        for frame in 0..frames {
            let sample = self.next_sample(phase_inc);
            output[frame * channels..(frame + 1) * channels].fill(sample);
        }

        self.stopped |= stopped;
        frames
    }

    fn get_param_mut(&mut self, name: &str) -> Option<&mut AudioParamTimeline> {
        match name {
            "frequency" => {
                self.frequency_values.reserve(
                    crate::audio_thread::RENDER_QUANTUM_FRAMES
                        .saturating_sub(self.frequency_values.len()),
                );
                Some(&mut self.frequency)
            }
            "detune" => {
                self.detune_values.reserve(
                    crate::audio_thread::RENDER_QUANTUM_FRAMES
                        .saturating_sub(self.detune_values.len()),
                );
                Some(&mut self.detune)
            }
            _ => None,
        }
    }
}
